func writeClientMethod(output *strings.Builder, currentRoute clientRoute, currentHandler clientHandler) {
	name := operationID(currentRoute.ID, currentHandler.Method)
	pathParams := pathParameters(currentRoute.Path)
	method := strings.ToUpper(currentHandler.Method)
	input := "query?: Readonly<Record<string, string | number | boolean>>"
	if method == "POST" || method == "PUT" || method == "PATCH" {
		input = "body?: JsonObject"
	}
	if len(pathParams) > 0 {
		input = "path: Readonly<{ " + strings.Join(pathParams, ": string; ") + ": string }>, " + input
	}
	fmt.Fprintf(output, "  %s(%s): Promise<ApiResponse> {\n", name, input)
	pathExpression := strconvQuote(currentRoute.Path)
	if len(pathParams) > 0 {
		pathExpression = "pathWithParams(" + pathExpression + ", path)"
	}
	if method == "POST" || method == "PUT" || method == "PATCH" {
		fmt.Fprintf(output, "    return this.request(%q, %s, undefined, body)\n", method, pathExpression)
	} else {
		fmt.Fprintf(output, "    return this.request(%q, %s, query)\n", method, pathExpression)
	}
	output.WriteString("  }\n\n")
}

func operationID(routeID, method string) string {
	parts := strings.Split(routeID, "/")
	for index, part := range parts {
		part = strings.TrimPrefix(strings.TrimSuffix(part, "]"), "[")
		part = strings.TrimPrefix(part, "...")
		parts[index] = strings.NewReplacer("-", "_", ".", "_").Replace(part)
	}
	return strings.Join(append(parts, "route", strings.ToLower(method)), "_")
}

func pathParameters(path string) []string {
	parameters := make([]string, 0)
	for _, part := range strings.Split(path, "/") {
		if strings.HasPrefix(part, ":") {
			parameters = append(parameters, strings.TrimSuffix(strings.TrimPrefix(part, ":"), "*"))
		}
	}
	return parameters
}

func strconvQuote(value string) string {
	return fmt.Sprintf("%q", value)
}

